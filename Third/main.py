import numpy as np
import pandas as pd

# Исходные данные
p = 30
t0 = 3
n_years = 8

e = [51.0, 49.0, 47.3, 45.6, 45.1, 44.5, 43.2, 42.6, 41.8]
s = [10.2, 10.4, 10.8, 11.3, 11.7, 12.0, 12.4, 12.9, 13.4]
z = [12.2, 10.4, 8.8, 7.3, 6.2, 5.3, 4.5, 3.8, 3.2]

# Функция для расчёта эффекта при сохранении или замене
def keep_effect(t):
    return e[t] - z[t]

def replace_effect(t):
    return s[t] - p + e[0] - z[0]   # e[0]-z[0] = 51.0 - 12.2 = 38.8

# Обратный ход DP
# g[i][t] – максимальный эффект за последние i лет при возрасте t в начале этих i лет
# i = 1..8, t может быть от 0 до t0 + n_years (максимум 11)
max_age = t0 + n_years
g = np.full((n_years+1, max_age+1), -np.inf)
decision = np.full((n_years+1, max_age+1), '', dtype=object)  # 'K' или 'R'

# Базовый шаг i=1 (последний год)
for t in range(max_age+1):
    if t > 8:
        # Для t > 8 используем экстраполяцию (можно продлить e,s,z, но по условию достаточно)
        # Будем считать, что после 8 лет характеристики не меняются (берём последние)
        e_t = e[8]
        s_t = s[8]
        z_t = z[8]
    else:
        e_t = e[t]
        s_t = s[t]
        z_t = z[t]
    keep = e_t - z_t
    repl = s_t - p + e[0] - z[0]
    if keep >= repl:
        g[1][t] = keep
        decision[1][t] = 'K'
    else:
        g[1][t] = repl
        decision[1][t] = 'R'

# Рекуррентные шаги i=2..n_years
for i in range(2, n_years+1):
    for t in range(max_age+1):
        if t > 8:
            e_t = e[8]
            z_t = z[8]
            s_t = s[8]
        else:
            e_t = e[t]
            z_t = z[t]
            s_t = s[t]
        # Вариант "сохранить": возраст увеличится на 1
        if t+1 <= max_age:
            keep_val = e_t - z_t + g[i-1][t+1]
        else:
            keep_val = -np.inf
        # Вариант "заменить": после замены возраст станет 1 год (новое ТСЗИ)
        repl_val = s_t - p + (e[0] - z[0]) + g[i-1][1]
        if keep_val >= repl_val:
            g[i][t] = keep_val
            decision[i][t] = 'K'
        else:
            g[i][t] = repl_val
            decision[i][t] = 'R'

print("Задача о замене ТСЗИ (вариант 32)")
print(f"Цена нового ТСЗИ p = {p}")
print(f"Начальный возраст t0 = {t0}")
print(f"Плановый период = {n_years} лет")
print(f"Максимальный суммарный эффект за плановый период: {g[n_years][t0]:.2f}")

# Прямой ход – восстановление решений по годам
current_age = t0
solution = []
for year in range(1, n_years+1):
    i = n_years - year + 1   # сколько лет осталось, включая текущий
    dec = decision[i][current_age]
    solution.append(dec)
    if dec == 'K':
        # Сохранили: в следующем году возраст увеличится на 1
        current_age += 1
    else:
        # Заменили: в следующем году возраст станет 1 (новое средство)
        current_age = 1

print("\nОптимальная стратегия по годам (K – сохранить, R – заменить):")
for year, dec in enumerate(solution, start=1):
    print(f"  Год {year}: {dec}")

# Расчёт эффективности (по формулам из пособия)
# Нужно вычислить сумму затрат на покупку новых ТСЗИ (∑p_k),
# сумму затрат на обслуживание (∑z(t_m)),
# сумму возвращённой стоимости проданных ТСЗИ (∑s(t_k)).
# Исходное ТСЗИ уже было куплено ранее? По тексту, стоимость исходного ТСЗИ p0 = p (в примере p0=17). Обычно учитывается.
# Будем следовать примеру 1.5: считаем все покупки (включая начальное? В примере начальное не учтено? На самом деле в примере 1.5 начальное ТСЗИ уже есть, его стоимость не входит в ∑p_k, т.к. оно не покупалось в плановом периоде. Учитываются только замены.
# Исходное ТСЗИ не покупается в плановом периоде, поэтому ∑p_k – только замены.
# Затраты на обслуживание: для каждого года берём z(возраст ТСЗИ в этом году).
# Возвращённая стоимость: при замене продаётся старое ТСЗИ по цене s(его возраст).

# Восстановим возраст по годам
ages = [t0]
for dec in solution[:-1]:
    if dec == 'K':
        ages.append(ages[-1] + 1)
    else:
        ages.append(1)
# Теперь ages[0] – возраст в начале года 1, ages[1] – возраст в начале года 2, ..., ages[7] – возраст в начале года 8.
# Затраты на обслуживание за год j: z( age в начале года j )
sum_z = 0
for age in ages:
    if age > 8:
        z_age = z[8]
    else:
        z_age = z[age]
    sum_z += z_age

# Затраты на покупку новых ТСЗИ: за каждую замену (кроме, возможно, первой, если решение 'R' в первый год?)
# По логике, если в первый год замена, то покупается новое ТСЗИ. Его стоимость p учитываем.
sum_p = 0
# Возвращённая стоимость: при замене в конце года (перед покупкой нового) продаётся старое.
# В примере 1.5: замены во 2-й и 5-й годы, сумма s(t) за эти годы.
sum_s = 0
for j, dec in enumerate(solution):
    if dec == 'R':
        sum_p += p
        age_sold = ages[j]   # возраст ТСЗИ в начале года, когда оно было заменено
        if age_sold > 8:
            s_age = s[8]
        else:
            s_age = s[age_sold]
        sum_s += s_age

# Итоговая эффективность Eff = F* / (sum_p + sum_z - sum_s)
F_star = g[n_years][t0]
denom = sum_p + sum_z - sum_s
eff = F_star / denom if denom != 0 else float('inf')

print("\nПоказатели эффективности")
print(f"Суммарные затраты на покупку новых ТСЗИ: {sum_p:.2f}")
print(f"Суммарные эксплуатационные затраты: {sum_z:.2f}")
print(f"Суммарная возвращённая стоимость: {sum_s:.2f}")
print(f"Общие затраты (с учётом возврата): {denom:.2f}")
print(f"Среднегодовой эффект: {F_star / n_years:.2f}")
print(f"Эффективность применения ТСЗИ: {eff:.3f}")

# Вывод для отчёта
print("\nПояснение")
print("Эффективность показывает, сколько условных единиц эффекта приходится на 1 условную единицу затрат.")
if eff > 1:
    print("Эффективность >1 – затраты окупаются.")
else:
    print("Эффективность ≤1 – затраты не окупаются.")